def genre_label(codes) -> str:
    if not codes:
        return ""
    if isinstance(codes, str):
        codes = [codes]
    seen: list[str] = []
    for code in codes:
        code = (code or "").strip()
        if not code:
            continue
        label = GENRE_LABELS.get(code.lower(), code.replace("_", " ").capitalize())
        if label not in seen:
            seen.append(label)
    return ", ".join(seen[:3])
